// ── scripts/lib/personaVoiceHouseStyle.ts ───────────────────────────────────
// Plan the em-dash sweep of entity_persona.voice_paragraph (#704).
//
// Every seeded voice paragraph is personaFactory output: the archetype for the
// entity's kind with its display name substituted. #702 swept the archetypes
// for em dashes, but the stored rows were written before that, so they still
// carry them. Regenerating from the swept factory gives the same paragraph with
// the new punctuation, and nothing else may change: this planner proves that
// per row (same words, same order, only punctuation and spacing differ) and
// sets aside any row where regeneration would change the content (an enriched
// or hand-edited paragraph), so those are never overwritten.
//
// Pure: no I/O. scripts/persona-voice-house-style.ts feeds it production rows
// and writes the guarded migration.

import { createHash } from 'node:crypto';

import { createPersona, type FactoryEntityInput } from '../../src/features/agents/logic/personaFactory';
import { EM_DASH } from './fanCopy';

export interface PersonaRow {
  entity_id: string;
  voice_paragraph: string;
}

export type EntityRow = Pick<FactoryEntityInput, 'id' | 'kind' | 'name' | 'display_name'>;

export interface VoiceRewrite {
  entity_id: string;
  kind: string;
  name: string;
  /** md5 of the live paragraph: the migration's guard. */
  oldMd5: string;
  old: string;
  next: string;
}

export interface VoicePlan {
  rewrites: VoiceRewrite[];
  /** Rows whose regenerated paragraph says something different. Never written. */
  differs: Array<{ entity_id: string; kind: string; name: string; live: string; regenerated: string }>;
  /** Persona rows with an em dash but no entity row (cannot be regenerated). */
  orphans: string[];
}

/** md5 hex of a string as UTF-8, the same value as Postgres md5(text). */
export function md5(s: string): string {
  return createHash('md5').update(s, 'utf8').digest('hex');
}

/** True when two texts have the same words in the same order (case and punctuation aside). */
export function sameWords(a: string, b: string): boolean {
  const words = (s: string) => s.toLowerCase().match(/[\p{L}\p{N}']+/gu)?.join(' ') ?? '';
  return words(a) === words(b);
}

/** The voice paragraph the swept factory writes for one entity. */
export function regeneratedVoice(entity: EntityRow): string {
  return createPersona({ entity: { ...entity, meta: null }, traits: [], relationships: [] }).voice_paragraph;
}

export function planVoiceRewrites(personas: readonly PersonaRow[], entities: readonly EntityRow[]): VoicePlan {
  const byId = new Map(entities.map((e) => [e.id, e]));
  const plan: VoicePlan = { rewrites: [], differs: [], orphans: [] };
  const dashed = personas
    .filter((p) => p.voice_paragraph.includes(EM_DASH))
    .sort((a, b) => (a.entity_id < b.entity_id ? -1 : a.entity_id > b.entity_id ? 1 : 0));
  for (const p of dashed) {
    const e = byId.get(p.entity_id);
    if (!e) {
      plan.orphans.push(p.entity_id);
      continue;
    }
    const next = regeneratedVoice(e);
    if (next.includes(EM_DASH) || !sameWords(p.voice_paragraph, next)) {
      plan.differs.push({ entity_id: p.entity_id, kind: e.kind, name: e.name, live: p.voice_paragraph, regenerated: next });
      continue;
    }
    plan.rewrites.push({ entity_id: p.entity_id, kind: e.kind, name: e.name, oldMd5: md5(p.voice_paragraph), old: p.voice_paragraph, next });
  }
  return plan;
}

/**
 * Fingerprint of a set of (entity_id, paragraph) pairs, the same value as
 *   md5(string_agg(entity_id::text || ':' || md5(voice_paragraph), ',' ORDER BY entity_id::text))
 * in Postgres (ids are lowercase uuids, so code-unit order equals C collation).
 */
export function fingerprint(rows: ReadonlyArray<{ entity_id: string; text: string }>): string {
  const sorted = [...rows].sort((a, b) => (a.entity_id < b.entity_id ? -1 : a.entity_id > b.entity_id ? 1 : 0));
  return md5(sorted.map((r) => `${r.entity_id}:${md5(r.text)}`).join(','));
}

/** Read-only check to run after applying: the fingerprint of the rewritten rows. */
export function renderVoiceVerify(plan: VoicePlan): string {
  const fp = fingerprint(plan.rewrites.map((r) => ({ entity_id: r.entity_id, text: r.next })));
  const ids = plan.rewrites.map((r) => `'${r.entity_id}'`);
  return [
    '-- Verify migration 0104 (persona voice house style, #704). Read only.',
    `-- Expected after applying: fp = ${fp}, n = ${ids.length}, dashed = 0.`,
    '-- Before applying, the same query returns the live snapshot fingerprint',
    `-- ${fingerprint(plan.rewrites.map((r) => ({ entity_id: r.entity_id, text: r.old })))}.`,
    '-- GENERATED by `npx tsx scripts/persona-voice-house-style.ts`.',
    "SELECT md5(string_agg(entity_id::text || ':' || md5(voice_paragraph), ',' ORDER BY entity_id::text)) AS fp,",
    '       count(*) AS n,',
    "       count(*) FILTER (WHERE position(U&'\\2014' IN voice_paragraph) > 0) AS dashed",
    'FROM   entity_persona',
    'WHERE  entity_id IN (',
    ...ids.map((id, i) => `  ${id}${i < ids.length - 1 ? ',' : ''}`),
    ');',
    '',
  ].join('\r\n');
}

/** Dollar-quote tag that cannot collide with the paragraphs. */
const TAG = '$voice$';

/** The guarded, idempotent migration for a plan. Lines joined with CRLF like the repo's other migrations. */
export function renderVoiceMigration(plan: VoicePlan, snapshotDate: string): string {
  for (const r of plan.rewrites) if (r.next.includes(TAG)) throw new Error(`quote tag inside paragraph for ${r.entity_id}`);
  const fp = fingerprint(plan.rewrites.map((r) => ({ entity_id: r.entity_id, text: r.next })));
  const kinds = new Map<string, number>();
  for (const r of plan.rewrites) kinds.set(r.kind, (kinds.get(r.kind) ?? 0) + 1);
  const kindLine = [...kinds].sort((a, b) => b[1] - a[1]).map(([k, n]) => `${k} ${n}`).join(', ');
  const n = plan.rewrites.length;
  const L: string[] = [
    '-- 0104_persona_voice_house_style.sql',
    '--',
    '-- House style for entity_persona.voice_paragraph: no em dashes (issue #704).',
    '--',
    `-- ${n} seeded voice paragraphs still carry the em dashes of the persona`,
    '-- archetypes they were written from. #702 swept those archetypes',
    '-- (src/features/agents/logic/personaFactory.ts), so each paragraph here is',
    '-- simply regenerated from the swept factory: the same words in the same',
    '-- order, only the punctuation changes (checked row by row by the generator).',
    `-- By kind: ${kindLine}.`,
    '--',
    `-- GUARDED AND IDEMPOTENT: each row carries the md5 of its paragraph as read`,
    `-- from production on ${snapshotDate}. A row is updated only while it still`,
    '-- holds exactly that text, so a paragraph enriched or edited since is',
    '-- skipped, and a second run updates nothing.',
    '--',
    '-- VERIFY after applying: docs/db-house-style.md has the query; over these',
    `-- ${n} rows it must return fingerprint ${fp}.`,
    '--',
    '-- GENERATED by `npx tsx scripts/persona-voice-house-style.ts`. Do not edit.',
    '',
    'DO $do$',
    'DECLARE',
    '  n_updated integer;',
    'BEGIN',
    '  UPDATE entity_persona p',
    '  SET    voice_paragraph = v.next',
    '  FROM (VALUES',
    ...plan.rewrites.map(
      (r, i) => `    ('${r.entity_id}', '${r.oldMd5}', ${TAG}${r.next}${TAG})${i < n - 1 ? ',' : ''}`,
    ),
    '  ) AS v(entity_id, old_md5, next)',
    '  WHERE  p.entity_id = v.entity_id::uuid',
    '    AND  md5(p.voice_paragraph) = v.old_md5;',
    '  GET DIAGNOSTICS n_updated = ROW_COUNT;',
    `  RAISE NOTICE '0104: % of % voice paragraphs updated (the rest had changed since the snapshot or were already done)', n_updated, ${n};`,
    'END',
    '$do$;',
    '',
  ];
  return L.join('\r\n');
}
